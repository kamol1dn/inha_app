"""Generates the launcher icon, the splash and the notification icon.

Usage: python tool/make_icons.py android/app/src/main/res [preview.png]

DESIGN.md 12: "IUT" in Fraunces SemiBold, ink on paper, with a short IUT-blue
rule under it. The letters are the bundled font's own outlines
(assets/fonts/FrauncesDisplay-SemiBold.ttf), laid out on the 108x108
adaptive-icon grid inside its 66-unit safe zone. The splash draws the same
mark in colours that follow the night mode. The status-bar icon stays a
white-on-transparent block wordmark: serifs vanish at 24 dp.
"""
import os
import sys

from fontTools.pens.basePen import BasePen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw

RES = sys.argv[1]  # android/app/src/main/res
FONT = os.path.join(os.path.dirname(__file__), '..', 'assets', 'fonts', 'FrauncesDisplay-SemiBold.ttf')

# DESIGN.md 3.
PAPER, INK, ACCENT = '#F5F2EA', '#1C1B19', '#1D4E89'
NIGHT, NIGHT_TEXT, NIGHT_ACCENT = '#1A1814', '#EDE7DA', '#9DBDE6'

CAP = 23.0  # cap height on the 108 grid
GAP, RULE_W, RULE_H = 5.5, 20.0, 3.0  # the rule under the letters


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def hex_rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


font = TTFont(FONT)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
names = [cmap[ord(c)] for c in 'IUT']
scale = CAP / font['OS/2'].sCapHeight

# Ink bounds of the word at its natural advances (font units, y up).
bounds = BoundsPen(glyphs)
x = 0
for n in names:
    glyphs[n].draw(TransformPen(bounds, (1, 0, 0, 1, x, 0)))
    x += font['hmtx'][n][0]
x_min, _, x_max, _ = bounds.bounds
width = (x_max - x_min) * scale
block = CAP + GAP + RULE_H
left, baseline = 54 - width / 2, 54 - block / 2 + CAP


def draw_word(pen):
    """Draws "IUT" onto [pen] in 108-grid coordinates (y down)."""
    x = 0
    for n in names:
        # font units -> grid: scale, flip y, move the ink box into place.
        t = (scale, 0, 0, -scale, left + (x - x_min) * scale, baseline)
        glyphs[n].draw(TransformPen(pen, t))
        x += font['hmtx'][n][0]


svg = SVGPathPen(glyphs, ntos=lambda v: f'{v:.2f}'.rstrip('0').rstrip('.'))
draw_word(svg)
LETTERS = svg.getCommands()
rule_x, rule_y = 54 - RULE_W / 2, baseline + GAP
RULE = f'M{rule_x:g},{rule_y:g} h{RULE_W:g} v{RULE_H:g} h-{RULE_W:g} z'


def vector(comment, letters_color, rule_color, size=108):
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- {comment} Generated by tool/make_icons.py. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:fillColor="{letters_color}" android:pathData="{LETTERS}" />
    <path android:fillColor="{rule_color}" android:pathData="{RULE}" />
</vector>
'''


# Adaptive icon (Android 8+): paper, ink letters, the blue rule. The themed
# layer (Android 13+) is the same mark in one colour; the system tints it.
write(f'{RES}/drawable/ic_launcher_foreground.xml',
      vector('"IUT" in Fraunces, ink, over the IUT-blue rule.', INK, ACCENT))
write(f'{RES}/drawable/ic_launcher_monochrome.xml',
      vector('Themed-icon layer (Android 13+): the system tints it.', '#FFFFFF', '#FFFFFF'))
write(f'{RES}/values/ic_launcher_background.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- DESIGN.md 3: the paper. -->
    <color name="ic_launcher_background">{PAPER}</color>
</resources>
''')
write(f'{RES}/mipmap-anydpi-v26/ic_launcher.xml', '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
''')

# Splash: the mark on paper by day, on ink at night, until Flutter draws.
for folder, (bg, text, accent) in {'values': (PAPER, INK, ACCENT), 'values-night': (NIGHT, NIGHT_TEXT, NIGHT_ACCENT)}.items():
    write(f'{RES}/{folder}/splash_colors.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- DESIGN.md 3 and 12: the splash in the {"night" if folder.endswith("night") else "day"} palette. -->
    <color name="splash_background">{bg}</color>
    <color name="splash_ink">{text}</color>
    <color name="splash_accent">{accent}</color>
</resources>
''')
write(f'{RES}/drawable/ic_splash.xml', vector('The splash mark; its colours follow the night mode.',
                                              '@color/splash_ink', '@color/splash_accent'))
for folder in ('drawable', 'drawable-v21'):
    write(f'{RES}/{folder}/launch_background.xml', '''<?xml version="1.0" encoding="utf-8"?>
<!-- Before Android 12: paper (ink at night) with the mark in the middle. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/splash_background" />
    <item android:drawable="@drawable/ic_splash" android:gravity="center"
        android:width="216dp" android:height="216dp" />
</layer-list>
''')
for folder, parent in (('values', 'Theme.Light.NoTitleBar'), ('values-night', 'Theme.Black.NoTitleBar')):
    night = folder.endswith('night')
    # Dark status-bar icons on paper; the night themes keep the light ones.
    bar = '' if night else '\n        <item name="android:windowLightStatusBar">true</item>'
    write(f'{RES}/{folder}/styles.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <!-- While the process starts, {"in night mode" if night else "by day"}: the splash (drawable/launch_background). -->
    <style name="LaunchTheme" parent="@android:style/{parent}">
        <item name="android:windowBackground">@drawable/launch_background</item>{bar}
    </style>
    <!-- Behind the Flutter UI while it starts and runs: the paper, so there is no white flash. -->
    <style name="NormalTheme" parent="@android:style/{parent}">
        <item name="android:windowBackground">@color/splash_background</item>{bar}
    </style>
</resources>
''')
    # Android 12+ draws its own splash: the background and the mark, no icon plate.
    write(f'{RES}/{folder}-v31/styles.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<resources>
    <style name="LaunchTheme" parent="@android:style/{parent}">
        <item name="android:windowBackground">@drawable/launch_background</item>
        <item name="android:windowSplashScreenBackground">@color/splash_background</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/ic_splash</item>{bar}
    </style>
    <style name="NormalTheme" parent="@android:style/{parent}">
        <item name="android:windowBackground">@color/splash_background</item>{bar}
    </style>
</resources>
''')

# Status bar icon: white on transparent, block letters filling the 24dp box
# (the viewport is the letters' box, x 25..83, y 39..69, plus 3 around).
BLOCK = ' '.join([
    'M25,39 h6 v30 h-6 z',
    'M37,39 h6 v19 a5,5 0 0 0 10,0 v-19 h6 v19 a11,11 0 0 1 -22,0 z',
    'M63,39 h20 v6 h-7 v24 h-6 v-24 h-7 z',
])
write(f'{RES}/drawable/ic_stat_notify.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Notification small icon: white on transparent (Android tints it). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="64"
    android:viewportHeight="64">
    <group android:translateX="-22" android:translateY="-22">
        <path android:fillColor="#FFFFFF" android:pathData="{BLOCK}" />
    </group>
</vector>
''')
write(f'{RES}/raw/keep.xml', '''<?xml version="1.0" encoding="utf-8"?>
<!-- R8 resource shrinking can't see icons named only from Dart (flutter_local_notifications). -->
<resources xmlns:tools="http://schemas.android.com/tools"
    tools:keep="@drawable/ic_stat_notify,@mipmap/ic_launcher" />
''')


class PolygonPen(BasePen):
    """Flattens outlines into polygons, for the legacy PNGs."""

    def __init__(self, glyph_set, steps=12):
        super().__init__(glyph_set)
        self.polygons, self.steps = [], steps

    def _moveTo(self, p):
        self.polygons.append([p])

    def _lineTo(self, p):
        self.polygons[-1].append(p)

    def _qCurveToOne(self, p1, p2):
        p0 = self.polygons[-1][-1]
        for i in range(1, self.steps + 1):
            t = i / self.steps
            self.polygons[-1].append(tuple((1 - t) ** 2 * a + 2 * (1 - t) * t * b + t * t * c for a, b, c in zip(p0, p1, p2)))

    def _curveToOne(self, p1, p2, p3):
        p0 = self.polygons[-1][-1]
        for i in range(1, self.steps + 1):
            t = i / self.steps
            self.polygons[-1].append(tuple(
                (1 - t) ** 3 * a + 3 * (1 - t) ** 2 * t * b + 3 * (1 - t) * t * t * c + t ** 3 * d
                for a, b, c, d in zip(p0, p1, p2, p3)))

    def _closePath(self):
        pass


polygons = PolygonPen(glyphs)
draw_word(polygons)


# Legacy PNGs (Android 7.x): a rounded square of paper with the mark, the
# mark scaled up a little since there is no adaptive-icon mask to crop it.
def legacy(n):
    k = 4  # supersample
    size = n * k
    img = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    margin = round(size * 0.04)
    d.rounded_rectangle([margin, margin, size - margin - 1, size - margin - 1], radius=round(size * 0.22),
                        fill=hex_rgb(PAPER) + (255,))
    s = 1.45 * size / 108

    def p(x, y):
        return ((x - 54) * s + size / 2, (y - 54) * s + size / 2)

    for poly in polygons.polygons:
        d.polygon([p(x, y) for x, y in poly], fill=hex_rgb(INK) + (255,))
    d.rectangle([p(rule_x, rule_y), p(rule_x + RULE_W, rule_y + RULE_H)], fill=hex_rgb(ACCENT) + (255,))
    return img.resize((n, n), Image.LANCZOS)


for folder, n in [('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)]:
    legacy(n).save(f'{RES}/mipmap-{folder}/ic_launcher.png')

if len(sys.argv) > 2:  # optional: a 512 px preview, e.g. for a store listing
    legacy(512).save(sys.argv[2])
